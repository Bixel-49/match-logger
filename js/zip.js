function decodeName(bytes, isUtf8) {
  try {
    return new TextDecoder('utf-8', { fatal: !isUtf8 }).decode(bytes);
  } catch {
    return Array.from(bytes, (b) => (b < 0x80 ? String.fromCharCode(b) : CP850[b - 0x80])).join('');
  }
}

async function inflateRaw(bytes) {
  const stream = new Blob([bytes]).stream().pipeThrough(new DecompressionStream('deflate-raw'));
  return new Uint8Array(await new Response(stream).arrayBuffer());
}

// Blob/File -> [{ path, content (string) }] (dossiers ignores)
export async function readZip(blob) {
  const buffer = await blob.arrayBuffer();
  const view = new DataView(buffer);
  const bytes = new Uint8Array(buffer);

  let endPos = -1;
  for (let i = buffer.byteLength - 22; i >= Math.max(0, buffer.byteLength - 65557); i--) {
    if (view.getUint32(i, true) === 0x06054b50) {
      endPos = i;
      break;
    }
  }
  if (endPos < 0) throw new Error('Fichier ZIP invalide');

  const count = view.getUint16(endPos + 10, true);
  let pos = view.getUint32(endPos + 16, true);
  const utf8 = new TextDecoder('utf-8');
  const files = [];

  for (let i = 0; i < count; i++) {
    if (view.getUint32(pos, true) !== 0x02014b50) throw new Error('Fichier ZIP corrompu');
    const flags = view.getUint16(pos + 8, true);
    const method = view.getUint16(pos + 10, true);
    const compressedSize = view.getUint32(pos + 20, true);
    const nameLength = view.getUint16(pos + 28, true);
    const extraLength = view.getUint16(pos + 30, true);
    const commentLength = view.getUint16(pos + 32, true);
    const localOffset = view.getUint32(pos + 42, true);
    const nameBytes = bytes.subarray(pos + 46, pos + 46 + nameLength);
    const path = decodeName(nameBytes, Boolean(flags & 0x0800)).replace(/\\/g, '/');
    pos += 46 + nameLength + extraLength + commentLength;

    if (path.endsWith('/')) continue;
    const dataStart = localOffset + 30 + view.getUint16(localOffset + 26, true) + view.getUint16(localOffset + 28, true);
    const raw = bytes.subarray(dataStart, dataStart + compressedSize);
    let data;
    if (method === 0) data = raw;
    else if (method === 8) data = await inflateRaw(raw);
    else throw new Error(`Compression non supportée pour ${path}`);
    files.push({ path, content: utf8.decode(data) });
  }
  return files;
}
